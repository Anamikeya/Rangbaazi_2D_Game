"""Generates the 31 arena stages for the sim from the art pack's level files.

    python tools/gen_arena_stages.py <art pack folder>   (e.g. .../game-art/round-brawler-v6)

Reads levels/<id>/level.json (the "discovery" layout: 1280 x 720 px, floor top at y = 650) and
writes the same stages twice, so the C# reference sim (and the server) and the GDScript sim build
them from identical exact ratios:

    src/Rangbaazi.Sim/ArenaStages.cs
    client/sim/arena_stages.gd

Conversion: 40 px per metre, x from the centre (640 px), y up from the floor's top (650 px). Every
arena gets the same eight spawn points on the floor and a blast zone 10 m beyond the 32 m stage.
Shan's arena keeps the id "rooftops" (Stages.Rooftops). Re-run after the art pack's level layouts
change; the golden traces only use "rooftops", whose numbers this must not change.
"""
import json
import os
import sys
from math import gcd

PX_PER_M = 40
CENTRE_X = 640
FLOOR_Y = 650
SPAWNS = [-11, 11, -4, 4, -8, 8, -1, 1]
SPAWN_Y = 2
BLAST = (-26, -10, 26, 22)
ID_FOR = {"shahn": "rooftops"}


def ratio(n, d=PX_PER_M):
    g = gcd(abs(n), d)
    return n // g, d // g


def cs(t):
    return f"Fix.FromInt({t[0]})" if t[1] == 1 else f"Fix.FromRatio({t[0]}, {t[1]})"


def gd(t):
    return f"Fx.from_int({t[0]})" if t[1] == 1 else f"Fx.ratio({t[0]}, {t[1]})"


def rects(level):
    out = []
    for p in level["layouts"][0]["platforms"]:
        out.append((
            ratio(p["x"] - CENTRE_X), ratio(FLOOR_Y - p["y"] - p["h"]),
            ratio(p["x"] + p["w"] - CENTRE_X), ratio(FLOOR_Y - p["y"]), p["id"]))
    return out


def main():
    pack = sys.argv[1]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    arenas = []
    for folder in sorted(os.listdir(os.path.join(pack, "levels"))):
        path = os.path.join(pack, "levels", folder, "level.json")
        if not os.path.exists(path):
            continue
        level = json.load(open(path, encoding="utf-8"))
        arenas.append((ID_FOR.get(folder, folder), folder, level["title"], rects(level)))

    c = ["// <auto-generated> by tools/gen_arena_stages.py from the art pack's levels/*/level.json. Don't edit by hand.", "#nullable enable",
         "using System.Collections.Generic;", "using Rangbaazi.Sim.FixedMath;", "", "namespace Rangbaazi.Sim;", "",
         "/// <summary>",
         "/// The 31 arena stages (one per fighter's home arena), converted from the art pack's layouts at",
         "/// 40 px per metre. Same numbers as client/sim/arena_stages.gd.",
         "/// </summary>",
         "public static class ArenaStages", "{",
         "    private static readonly FixVec2[] Spawns =", "    {"]
    for x in SPAWNS:
        c.append(f"        new FixVec2(Fix.FromInt({x}), Fix.FromInt({SPAWN_Y})),")
    c += ["    };", "",
          f"    private static readonly FixRect Blast = new(Fix.FromInt({BLAST[0]}), Fix.FromInt({BLAST[1]}), Fix.FromInt({BLAST[2]}), Fix.FromInt({BLAST[3]}));", "",
          "    /// <summary>Every arena stage, in a fixed order (by art folder name).</summary>",
          "    public static readonly IReadOnlyList<StageDefinition> All = new[]", "    {"]
    for sid, folder, title, rs in arenas:
        c.append(f"        // {title} ({folder})")
        c.append(f"        new StageDefinition {{ Id = \"{sid}\", SpawnPoints = Spawns, BlastZone = Blast, Platforms = new[]")
        c.append("        {")
        for r in rs:
            c.append(f"            new FixRect({cs(r[0])}, {cs(r[1])}, {cs(r[2])}, {cs(r[3])}), // {r[4]}")
        c.append("        } },")
    c += ["    };", "",
          "    /// <summary>The arena stage with this id, or null.</summary>",
          "    public static StageDefinition? ById(string id)", "    {",
          "        foreach (StageDefinition s in All) if (s.Id == id) return s;",
          "        return null;", "    }", "}", ""]
    open(os.path.join(root, "src", "Rangbaazi.Sim", "ArenaStages.cs"), "w", encoding="utf-8", newline="\n").write("\n".join(c))

    g = ["class_name ArenaStages",
         "## Generated by tools/gen_arena_stages.py from the art pack's levels/*/level.json: don't edit by",
         "## hand. The 31 arena stages, the same numbers as src/Rangbaazi.Sim/ArenaStages.cs.", "",
         "## Arena stage ids in a fixed order, with the art folder and the arena's name.",
         "const IDS := ["]
    for sid, folder, title, _ in arenas:
        g.append(f"\t[\"{sid}\", \"{folder}\", \"{title}\"],")
    g += ["]", "", "static var _cache: Dictionary = {}", "", "",
          "## The arena stage with this id, or null.",
          "static func by_id(stage_id: String) -> StageDefinition:",
          "\tif _cache.has(stage_id):", "\t\treturn _cache[stage_id]",
          "\tvar platforms: Array[FxRect] = []", "\tmatch stage_id:"]
    for sid, folder, title, rs in arenas:
        g.append(f"\t\t\"{sid}\": # {title}")
        g.append("\t\t\tplatforms = [")
        for r in rs:
            g.append(f"\t\t\t\tFxRect.new({gd(r[0])}, {gd(r[1])}, {gd(r[2])}, {gd(r[3])}), # {r[4]}")
        g.append("\t\t\t]")
    g += ["\t\t_:", "\t\t\treturn null",
          "\tvar s := StageDefinition.new()", "\ts.id = stage_id", "\ts.platforms = platforms",
          "\ts.spawn_x = PackedInt64Array([" + ", ".join(f"Fx.from_int({x})" for x in SPAWNS) + "])",
          "\ts.spawn_y = PackedInt64Array([" + ", ".join(f"Fx.from_int({SPAWN_Y})" for _ in SPAWNS) + "])",
          f"\ts.blast_zone = FxRect.new(Fx.from_int({BLAST[0]}), Fx.from_int({BLAST[1]}), Fx.from_int({BLAST[2]}), Fx.from_int({BLAST[3]}))",
          "\t_cache[stage_id] = s", "\treturn s", "",
          "", "## The art folder for an arena stage id (\"rooftops\" is Shan's), or \"\".",
          "static func art_folder(stage_id: String) -> String:",
          "\tfor e: Array in IDS:", "\t\tif e[0] == stage_id:", "\t\t\treturn e[1]", "\treturn \"\"", "",
          "", "static func title(stage_id: String) -> String:",
          "\tfor e: Array in IDS:", "\t\tif e[0] == stage_id:", "\t\t\treturn e[2]", "\treturn stage_id", ""]
    open(os.path.join(root, "client", "sim", "arena_stages.gd"), "w", encoding="utf-8", newline="\n").write("\n".join(g))
    print(f"{len(arenas)} arenas written")


if __name__ == "__main__":
    main()
